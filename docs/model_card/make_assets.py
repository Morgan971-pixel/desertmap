"""Build the data-driven assets for the DesertMap model card.

Run from the repo root:  uv run python docs/model_card/make_assets.py
Reads site/data/summary.json and writes, next to this file:
  numbers.tex       one LaTeX macro per figure quoted in the card
  fig_holc.pdf      predicted food-desert rate by HOLC grade
  fig_shap.pdf      global SHAP importance by feature
"""
from __future__ import annotations

import json
import pathlib

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
from matplotlib import font_manager  # noqa: E402

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
SUMMARY = ROOT / "site" / "data" / "summary.json"

INK = "#1f2937"
MUTED = "#6b7280"
GRID = "#e5e7eb"
ORANGE = "#f97316"
GRADE_COLORS = {"A": "#22c55e", "B": "#3b82f6", "C": "#f59e0b", "D": "#ef4444"}
GRADE_NAMES = {"A": "Best", "B": "Still desirable", "C": "Declining", "D": "Hazardous"}
FIG_WIDTH = 3.3  # inches; one column of the card is about 3.5 in

# The card is set in Source Sans Pro, which tectonic downloads into its cache.
FONT_CACHE_GLOBS = [
    "Library/Caches/TectonicProject.Tectonic/bundles/**/SourceSansPro-*.otf",
    ".cache/Tectonic/bundles/**/SourceSansPro-*.otf",
]


def use_card_font() -> str:
    home = pathlib.Path.home()
    found = [p for g in FONT_CACHE_GLOBS for p in home.glob(g)]
    for path in found:
        font_manager.fontManager.addfont(str(path))
    family = "Source Sans Pro" if found else "DejaVu Sans"
    plt.rcParams.update({
        "font.family": family,
        "font.size": 8,
        "axes.edgecolor": GRID,
        "axes.labelcolor": INK,
        "axes.titlesize": 8.5,
        "text.color": INK,
        "xtick.color": INK,
        "ytick.color": INK,
        "xtick.major.size": 0,
        "ytick.major.size": 0,
        "figure.facecolor": "white",
        "axes.facecolor": "white",
        "pdf.fonttype": 42,
    })
    return family


def pct(x: float, nd: int = 1) -> str:
    return f"{x * 100:.{nd}f}"


def thousands(n: int) -> str:
    return f"{n:,}".replace(",", "{,}")


def write_numbers(s: dict) -> None:
    holc, fair, met = s["holc"], s["fairness"], s["metrics"]
    rf, lr = met["random_forest"], met["logistic_regression"]
    shap_total = sum(r["total"] for r in s["global_shap"])
    shares = {r["feature"]: r["total"] / shap_total for r in s["global_shap"]}
    race = ("pct_nhblack10", "pct_hisp10", "pct_nhwhite10")
    share = s["food_desert_share"]

    macros = {
        "NTracts": thousands(s["n_tracts"]),
        "NMapped": thousands(s["n_mapped"]),
        "FoodDesertShare": pct(share) + r"\%",
        "ImbalanceRatio": f"{(1 - share) / share:.1f}",
        "HolcRatio": f"{holc['ratio']:.2f}",
        "HolcRatioTest": f"{holc['ratio_test']:.2f}",
        "HolcLabelRatio": f"{holc['label_ratio']:.2f}",
        "CdRate": pct(holc["cd_rate"]) + r"\%",
        "AbRate": pct(holc["ab_rate"]) + r"\%",
        "HolcN": thousands(sum(holc["counts"].values())),
        "FairFOne": f"{fair['f1_full']:.3f}",
        "FairFOneNoRace": f"{fair['f1_race_removed']:.3f}",
        "FairDeltaPts": f"{fair['f1_delta_pts']:.1f}",
        "FlipRate": pct(fair["counterfactual_flip_rate"]) + r"\%",
        "FprDisparity": f"{fair['fpr_disparity_q4_q1']:.1f}",
        "ShapIncomeShare": pct(shares["MedianFamilyIncome"], 0) + r"\%",
        "ShapPovertyShare": pct(shares["PovertyRate"], 0) + r"\%",
        "ShapRaceShare": pct(sum(shares[f] for f in race), 0) + r"\%",
    }
    for g in "ABCD":
        macros[f"HolcRate{g}"] = pct(holc["rates"][g]) + r"\%"
    names = {"f1": "FOne", "precision": "Prec", "recall": "Rec", "roc_auc": "Auc"}
    for key, tag in names.items():
        a, b = rf[key], lr[key]
        macros[f"Rf{tag}"] = f"{a:.3f}"
        macros[f"Lr{tag}"] = f"{b:.3f}"
        # Table cells: the better of the two models is wrapped in \best.
        macros[f"Rf{tag}Cell"] = (r"\best{%.3f}" if a > b else "%.3f") % a
        macros[f"Lr{tag}Cell"] = (r"\best{%.3f}" if b > a else "%.3f") % b

    lines = ["% Generated by make_assets.py from site/data/summary.json. Do not edit."]
    lines += [rf"\newcommand{{\{k}}}{{{v}}}" for k, v in macros.items()]
    (HERE / "numbers.tex").write_text("\n".join(lines) + "\n")


def style_axes(ax, grid_axis: str) -> None:
    for side in ("top", "right", "left"):
        ax.spines[side].set_visible(False)
    ax.spines["bottom"].set_color(GRID)
    ax.grid(axis=grid_axis, color=GRID, linewidth=0.5)
    ax.set_axisbelow(True)


def holc_chart(s: dict) -> None:
    holc = s["holc"]
    grades = list("ABCD")
    rates = [holc["rates"][g] * 100 for g in grades]
    fig, ax = plt.subplots(figsize=(FIG_WIDTH, 2.35))
    bars = ax.bar(range(4), rates, width=0.62,
                  color=[GRADE_COLORS[g] for g in grades])
    for bar, r in zip(bars, rates):
        ax.text(bar.get_x() + bar.get_width() / 2, r + 0.6, f"{r:.1f}%",
                ha="center", va="bottom", fontsize=8, fontweight="semibold")

    # Pooled rates as a bracket over each pair of bars, clear of the value labels.
    for (lo, hi), name, rate in (((0, 1), "A+B", holc["ab_rate"]),
                                 ((2, 3), "C+D", holc["cd_rate"])):
        y = max(rates[lo], rates[hi]) + 4.6
        ax.plot([lo - 0.28, lo - 0.28, hi + 0.28, hi + 0.28], [y - 0.9, y, y, y - 0.9],
                color=MUTED, linewidth=0.7)
        ax.text((lo + hi) / 2, y + 0.5, f"{name} pooled: {pct(rate)}%",
                ha="center", va="bottom", fontsize=7.5, color=INK)
    ax.text(-0.42, 41.5, f"C+D rate is {holc['ratio']:.2f}× the A+B rate",
            ha="left", va="top", fontsize=8.5, fontweight="bold", color="#c2410c")

    ax.set_xticks(range(4))
    ax.set_xticklabels([f"{g}  {GRADE_NAMES[g]}\nn = {holc['counts'][g]:,}"
                        for g in grades], fontsize=7)
    ax.set_ylim(0, 42)
    ax.set_yticks([0, 10, 20, 30])
    ax.set_yticklabels([f"{t}%" for t in (0, 10, 20, 30)], fontsize=7, color=MUTED)
    ax.set_ylabel("Predicted food-desert rate", fontsize=7.5, color=MUTED)
    style_axes(ax, "y")
    fig.tight_layout(pad=0.2)
    fig.savefig(HERE / "fig_holc.pdf")
    plt.close(fig)


def shap_chart(s: dict) -> None:
    rows = sorted(s["global_shap"], key=lambda r: r["total"])  # smallest first, so largest plots on top
    total = sum(r["total"] for r in rows)
    shares = [r["total"] / total * 100 for r in rows]
    labels = [r["label"] for r in rows]
    fig, ax = plt.subplots(figsize=(FIG_WIDTH, 2.5))
    ax.barh(range(len(rows)), shares, height=0.66, color=ORANGE)
    for i, v in enumerate(shares):
        ax.text(v + 0.8, i, f"{v:.1f}%", va="center", fontsize=7, color=INK)
    ax.set_yticks(range(len(rows)))
    ax.set_yticklabels(labels, fontsize=7.5)
    ax.set_xlim(0, max(shares) * 1.16)
    ax.set_xticks([0, 10, 20, 30, 40, 50])
    ax.set_xticklabels([f"{t}%" for t in (0, 10, 20, 30, 40, 50)], fontsize=7, color=MUTED)
    ax.set_xlabel("Share of total |SHAP|", fontsize=7.5, color=MUTED)
    style_axes(ax, "x")
    fig.tight_layout(pad=0.2)
    fig.savefig(HERE / "fig_shap.pdf")
    plt.close(fig)


def main() -> None:
    summary = json.loads(SUMMARY.read_text())
    family = use_card_font()
    write_numbers(summary)
    holc_chart(summary)
    shap_chart(summary)
    print(f"Wrote numbers.tex, fig_holc.pdf, fig_shap.pdf to {HERE} (chart font: {family})")


if __name__ == "__main__":
    main()
